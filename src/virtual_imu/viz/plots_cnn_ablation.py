"""Paper-style, run-local figures for shared CNN-BiLSTM ablation tables.

No model/data loading: callers supply the tidy metric/cost summaries and the
per-seed module deltas generated by report_cnn_bilstm_ablation.py.
"""

# zip(strict=...) is unavailable in the pinned Python3.9 runtime.
# ruff: noqa: B905
from __future__ import annotations

import logging
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from virtual_imu.viz.style import COLORS, apply_paper_style, save_figure

LOG = logging.getLogger(__name__)
PRIMARY = ("cnn_bilstm", "bilstm_only", "cnn_only", "mlp_only", "cnn_lstm")
CONTROLS = ("cnn_lstm", "cnn_lstm_wide", "pointwise_bilstm", "cnn_bilstm_dense")
CELLS = (
    ("alimu_only", "alimu", "ALiMU shared / ALiMU"),
    ("pooled", "alimu", "Joint shared / ALiMU"),
    ("pooled", "penncosyvio", "Joint shared / Penn"),
)
LABELS = dict(
    cnn_bilstm="CNN-BiLSTM",
    bilstm_only="BiLSTM only",
    cnn_only="CNN only",
    mlp_only="MLP only",
    cnn_lstm="CNN-LSTM32",
    cnn_lstm_wide="CNN-LSTM64",
    pointwise_bilstm="Pointwise-BiLSTM",
    cnn_bilstm_dense="Dense loss",
)
PALETTE = dict(
    zip(PRIMARY, [COLORS["virtual"], COLORS["accent"], COLORS["low"], "#82718e", COLORS["high"]])
)
PALETTE.update(cnn_lstm_wide="#526777", pointwise_bilstm="#9b7860", cnn_bilstm_dense="#697e99")
UNITS = {"gyro_rmse": "rad/s", "accel_rmse": "m/s$^2$"}


def _save(fig, directory, stem, caption):
    paths = save_figure(fig, directory, stem)
    for path in paths:
        LOG.info("WRITES %s", path)
    return dict(stem=stem, caption=caption, paths=[str(p) for p in paths])


def _context_curves(summary, directory, config):
    fig, axes = plt.subplots(2, 3, figsize=(7.2, 5.0), layout="constrained")
    windows = sorted(config["windows"])
    for column, (protocol, dataset, title) in enumerate(CELLS):
        for row, metric in enumerate(UNITS):
            ax = axes[row, column]
            frame = summary[
                (summary.protocol == protocol)
                & (summary.dataset_id == dataset)
                & summary.split.eq("test")
                & summary.aggregation.eq("dataset")
                & summary.metric.eq(metric)
            ]
            for variant in config["variants"]:
                values = frame[frame.variant.eq(variant)].sort_values("window")
                if values.empty:
                    LOG.info("SKIPS empty curve %s/%s/%s/%s", protocol, dataset, variant, metric)
                    continue
                ax.errorbar(
                    values.window,
                    values["mean"],
                    yerr=values.sd.fillna(0),
                    marker="o",
                    markersize=3,
                    capsize=2,
                    color=PALETTE[variant],
                    label=LABELS[variant],
                )
            raw = frame[frame.variant.eq("raw")]
            if not raw.empty:
                ax.axhline(
                    raw["mean"].iloc[0],
                    color=COLORS["low"],
                    linestyle="--",
                    linewidth=1,
                    label="Raw",
                )
            if row == 0:
                ax.set_title(title)
            ax.set_xticks(windows, [str(w) for w in windows])
            ax.set_xlabel("Context [points]")
            ax.set_ylabel(f"{'Gyro' if row == 0 else 'Accel'} RMSE [{UNITS[metric]}]")
            ax.set_ylim(bottom=0)
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside lower center", ncols=3, frameon=False)
    return _save(
        fig,
        directory,
        "window_context_curves",
        f"TEST component RMSE on the identical central40 targets in common320 anchors, context lengths {windows} at {config['data'].get('rate_hz', 40)} Hz. "
        "Panels separate training protocol/evaluation dataset and physical units. Points and error bars are seed means and sample SD (ddof=1); Raw is one deterministic value. "
        "Curves describe context sensitivity; window selection uses only balanced VALID scores, and these TEST curves do not select a winner.",
    )


def _delta_bars(deltas, directory, variants, stem, caption):
    fig, axes = plt.subplots(2, 3, figsize=(7.2, 5.0), layout="constrained")
    for column, (protocol, dataset, title) in enumerate(CELLS):
        for row, metric in enumerate(UNITS):
            ax = axes[row, column]
            frame = deltas[
                (deltas.protocol == protocol)
                & deltas.dataset_id.eq(dataset)
                & deltas.split.eq("test")
                & deltas.aggregation.eq("dataset")
                & deltas.metric.eq(metric)
                & deltas.window.eq(320)
            ]
            for index, variant in enumerate(variants):
                values = frame[frame.variant.eq(variant)].relative_delta_pct.dropna()
                if values.empty:
                    LOG.info(
                        "SKIPS undefined/absent delta %s/%s/%s/%s",
                        protocol,
                        dataset,
                        variant,
                        metric,
                    )
                    continue
                mean = values.mean()
                sd = values.std(ddof=1) if len(values) > 1 else 0.0
                ax.barh(index, mean, height=0.65, color=PALETTE[variant], xerr=sd, capsize=2)
                ax.scatter(values, np.full(len(values), index), color=COLORS["high"], s=6, zorder=3)
            ax.axvline(0, color=COLORS["high"], linewidth=0.8)
            ax.set_yticks(range(len(variants)), [LABELS[v] for v in variants])
            ax.invert_yaxis()
            if row == 0:
                ax.set_title(title)
            ax.set_xlabel(f"{'Gyro' if row == 0 else 'Accel'} RMSE change [%]")
            ax.grid(axis="y", visible=False)
    return _save(
        fig,
        directory,
        stem,
        caption
        + " Per-seed dots and seed mean ± sample SD are shown. Positive values mean the treatment is worse than full; negative values mean it is better. "
        "Percentages are calculated within each identical seed/window/support pair before averaging; these are not recording confidence intervals. A zero reference gives an undefined percentage and is skipped.",
    )


def _compute_curves(compute, directory, protocol, config):
    fig, axes = plt.subplots(2, 2, figsize=(7.2, 5.0), layout="constrained")
    all_variants = list(config["variants"]) + list(config.get("supplemental", []))
    frame = compute[compute.protocol.eq(protocol)]
    for ax, metric, label in (
        (axes[0, 0], "parameters", "Parameters"),
        (axes[0, 1], "batch1_ms_median", "Batch1 latency [ms]"),
    ):
        for index, variant in enumerate(all_variants):
            values = frame[
                frame.variant.eq(variant) & frame.window.eq(320) & frame.metric.eq(metric)
            ]
            if values.empty:
                continue
            ax.barh(
                index,
                values["mean"].iloc[0],
                xerr=values.sd.fillna(0).iloc[0],
                color=PALETTE[variant],
                capsize=2,
                height=0.65,
            )
        ax.set_yticks(range(len(all_variants)), [LABELS[v] for v in all_variants])
        ax.invert_yaxis()
        ax.set_xlabel(label)
        ax.set_title(f"{protocol}, context320")
        ax.grid(axis="y", visible=False)
    for ax, metric, label in (
        (axes[1, 0], "batch1_ms_median", "Batch1 latency [ms]"),
        (axes[1, 1], "elapsed_seconds", "Fit wall time [s]"),
    ):
        for variant in config["variants"]:
            values = frame[frame.variant.eq(variant) & frame.metric.eq(metric)].sort_values(
                "window"
            )
            ax.errorbar(
                values.window,
                values["mean"],
                yerr=values.sd.fillna(0),
                color=PALETTE[variant],
                marker="o",
                markersize=3,
                capsize=2,
                label=LABELS[variant],
            )
        ax.set_xlabel("Context [points]")
        ax.set_xticks(sorted(config["windows"]))
        ax.set_ylabel(label)
        ax.set_ylim(bottom=0)
    handles, labels = axes[1, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside lower center", ncols=3, frameon=False)
    return _save(
        fig,
        directory,
        "compute_" + protocol,
        f"Measured compute costs for {protocol}: parameters and batch1 latency at context320, followed by latency and per-fit wall time across primary contexts. "
        "Latency is each seed's median over synchronized repeated forwards, summarized across seeds as mean ± sample SD. Wall time includes VALID and is affected by concurrency; latency is load-sensitive. "
        "Different architectures have different parameter counts; the dense control also changes TRAIN loss support.",
    )


def render_ablation_figures(summary, module_deltas, compute_summary, out_dir, config):
    """Export five figure bundles + figure_index.md, returning paths/captions.

    Uses virtual_imu.viz.style exclusively; every bundle contains PNG300dpi,
    SVG and PDF. Input frames are never modified and metrics are never refit.
    """
    directory = Path(out_dir)
    directory.mkdir(parents=True, exist_ok=True)
    apply_paper_style()
    LOG.info(
        "READS in-memory summary, paired module deltas and compute tables; SKIPS model loading"
    )
    entries = [_context_curves(summary, directory, config)]
    entries.append(
        _delta_bars(
            module_deltas,
            directory,
            [v for v in config["variants"] if v != "cnn_bilstm"],
            "module_delta_320",
            "TEST primary module interventions at context320 versus the same-seed full CNN-BiLSTM on common center40 targets.",
        )
    )
    controls = [v for v in CONTROLS if v in [*config["variants"], *config.get("supplemental", [])]]
    if controls:
        entries.append(
            _delta_bars(
                module_deltas,
                directory,
                controls,
                "control_delta_320",
                "TEST direction/capacity and loss-support controls at context320: single-direction hidden32/64, depth-preserving pointwise convolutions, and dense320 TRAIN loss. "
                "Dense loss is a sensitivity control, not a strict module factor. All controls evaluate the same center40 points.",
            )
        )
    for protocol in config["protocols"]:
        entries.append(_compute_curves(compute_summary, directory, protocol, config))
    seed_counts = sorted(summary.loc[~summary.variant.eq("raw"), "n"].unique().tolist())
    lines = [
        "# Shared CNN-BiLSTM ablation figures",
        "",
        f"Optimization repeats: n={seed_counts}; configured seeds={config['seeds']}. Bars/curves use sample SD across seeds, not confidence intervals over independent recordings. Raw n=1. "
        "Gyro and accel use separate panels and physical units. All static figures use repository style, double-column width7.2in and PNG300dpi/SVG/PDF exports.",
        "",
    ]
    for entry in entries:
        stem = entry["stem"]
        lines += [
            f"## {stem}",
            "",
            " · ".join(f"[{ext.upper()}]({stem}.{ext})" for ext in ("png", "svg", "pdf")),
            "",
            entry["caption"],
            "",
        ]
    index = directory / "figure_index.md"
    index.write_text("\n".join(lines), encoding="utf-8")
    LOG.info("WRITES %s", index)
    return entries
